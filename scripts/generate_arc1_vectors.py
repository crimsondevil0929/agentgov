def _canonical_vectors() -> dict[str, Any]:
    cases = [
        ("sorted-keys", {"b": 1, "a": 2, "c": {"z": True, "y": None}}),
        ("utf16-key-order", {"": 1, "\U0001f600": 2, "a": 3, "é": 4}),
        (
            "string-escapes",
            {
                "s": 'quote" backslash\\ newline\n tab\t ctrl\u0001 del\u007f nbsp'
                + chr(0xA0)
                + " ls"
                + chr(0x2028)
                + " "
                + chr(0x1F600)
            },
        ),
        ("integers", {"max": 2**53 - 1, "min": -(2**53 - 1), "zero": 0, "negative": -7}),
        ("nesting", {"a": [], "b": {}, "c": [[], [{}], [1, "x", False, None]]}),
    ]
    rejects = [
        ("float", '{"a":1.5}'),
        ("exponent", '{"a":1e3}'),
        ("duplicate-key", '{"a":1,"a":2}'),
        ("nan", '{"a":NaN}'),
        ("unsafe-integer", '{"a":9007199254740992}'),
    ]
    return {
        "description": "RFC 8785 canonical JSON restricted to the ARC1 value domain. "
        "Each 'accept' input must canonicalize to exactly 'canonical' (UTF-8); each "
        "'reject' text must fail to decode or to canonicalize.",
        "accept": [
            {"name": name, "input": value, "canonical": canonical_bytes(value).decode("utf-8")}
            for name, value in cases
        ],
        "reject": [{"name": name, "text": text} for name, text in rejects],
    }


def _merkle_vectors() -> dict[str, Any]:
    leaves = [
        bytes.fromhex(h)
        for h in (
            "",
            "00",
            "10",
            "2021",
            "3031",
            "40414243",
            "5051525354555657",
            "606162636465666768696a6b6c6d6e6f",
        )
    ]
    tree = MerkleTree(leaf_hash(leaf) for leaf in leaves)
    return {
        "description": "RFC 9162 section 2.1: the eight-leaf tree used by the Certificate "
        "Transparency test suites. Leaves are raw leaf data; hash them with "
        "SHA-256(0x00 || data).",
        "leaves": [leaf.hex() for leaf in leaves],
        "roots": [{"size": n, "root": tree.root(n).hex()} for n in range(len(leaves) + 1)],
        "inclusion": [
            {"index": m, "size": n, "path": [p.hex() for p in tree.inclusion_proof(m, n)]}
            for n in range(1, len(leaves) + 1)
            for m in range(n)
        ],
        "consistency": [
            {"old": m, "new": n, "proof": [p.hex() for p in tree.consistency_proof(m, n)]}
            for n in range(1, len(leaves) + 1)
            for m in range(n + 1)
        ],
    }


