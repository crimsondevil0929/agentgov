def generate(out: Path) -> None:
    """Write every vector file under ``out``, replacing what is there."""
    issuer = Ed25519Signer(seed("issuer"))
    witness_key = Ed25519Signer(seed("witness"))
    attacker = Ed25519Signer(seed("attacker"))
    internal = HmacKey(seed("internal hmac"))

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / "README.md").write_text(_README, encoding="utf-8")
    keys = out / "keys"
    keys.mkdir()
    (keys / "issuer.pub").write_text(issuer.public_key().spec() + "\n")
    (keys / "issuer.seed").write_text(seed("issuer").hex() + "\n")
    (keys / "witness.pub").write_text(witness_key.public_key().spec() + "\n")
    (keys / "witness.seed").write_text(seed("witness").hex() + "\n")
    (keys / "internal.hmac").write_text(internal.spec() + "\n")

    _write_json(out / "canonical.json", _canonical_vectors())
    _write_json(out / "merkle.json", _merkle_vectors())
    _write_json(out / "ed25519.json", _ed25519_vectors())

    scenarios = _scenarios()
    with tempfile.TemporaryDirectory() as scratch:
        work = Path(scratch)
        witness = FileWitness(
            work / "cosignatures.jsonl",
            witness_key,
            witness_id=WITNESS_ID,
            logs={LOG_ID: issuer.public_key()},
            clock=_Clock(_BASE + timedelta(hours=1), timedelta(minutes=5)),
        )
        log = ReceiptLog(
            LOG_ID,
            issuer,
            path=work / "receipts.jsonl",
            witnesses=[witness],
            policy=CheckpointPolicy(every_receipts=10**6, every_seconds=10**9),
            clock=_Clock(_BASE + timedelta(minutes=59), timedelta(minutes=1)),
        )
        receipts: dict[str, ActionReceipt] = {}
        commitments: dict[str, RowCommitment] = {}
        first: Checkpoint | None = None
        unwitnessed: Checkpoint | None = None
        for index, (name, draft, commitment) in enumerate(scenarios):
            receipts[name] = log.issue(draft)
            commitments[name] = commitment
            if index == 2:
                first = log.publish()
            if index == 4:
                unwitnessed = log.checkpoint()
        final = log.publish()
        assert first is not None
        consistency = log.consistency_proof(first.tree_size, final.tree_size)
        bundles = {name: log.bundle(i, final) for i, (name, _, _) in enumerate(scenarios)}
        log.close()
        (out / "log").mkdir()
        shutil.copy(work / "receipts.jsonl", out / "log" / "receipts.jsonl")
        shutil.copy(work / "receipts.jsonl.checkpoints", out / "log" / "receipts.jsonl.checkpoints")
        (out / "witness").mkdir()
        shutil.copy(work / "cosignatures.jsonl", out / "witness" / "cosignatures.jsonl")
    assert unwitnessed is not None

    _write_json(
        out / "log" / "consistency.json",
        {
            "description": "The witness checked this RFC 9162 consistency proof before it "
            "cosigned the second checkpoint.",
            "old": first.to_json(),
            "new": final.to_json(),
            "proof": [p.hex() for p in consistency],
        },
    )

    valid = out / "valid"
    for name in (
        "committed-refund",
        "refused-tenant-wipe",
        "scoped-repair",
        "recovered-commit",
        "halted-scope",
    ):
        _write_json(valid / f"{name}.bundle.json", bundles[name].to_json())
    refund, wipe = receipts["committed-refund"], receipts["refused-tenant-wipe"]
    refund_rows = commitments["committed-refund"].disclose([0, 2], receipt_id=refund.receipt_id)
    wipe_rows = commitments["refused-tenant-wipe"].disclose([5, 130], receipt_id=wipe.receipt_id)
    _write_json(valid / "committed-refund.rows.json", refund_rows.to_json())
    _write_json(valid / "refused-tenant-wipe.rows.json", wipe_rows.to_json())
    internal_receipt = replace(
        scenarios[1][1], receipt_id=_uuid("receipt:internal-hmac"), anchors=Anchors()
    ).sign(internal)
    _write_json(valid / "internal-hmac.receipt.json", internal_receipt.to_json())

    invalid = out / "invalid"
    good = bundles["committed-refund"].to_json()

    tampered = json.loads(json.dumps(good))
    tampered["receipt"]["cost"]["settled_usd"] = "0.00049500"
    _write_json(invalid / "field-modified.bundle.json", tampered)

    lowered = replace(refund, cost=replace(refund.cost, settled_usd=Decimal("0.00049500")))
    forged = lowered.sign(attacker)
    assert forged.signature is not None and refund.signature is not None
    forged = replace(
        forged,
        signature=Signature(forged.signature.alg, refund.signature.key_id, forged.signature.value),
    )
    _write_json(
        invalid / "forged-signature.bundle.json",
        replace(bundles["committed-refund"], receipt=forged).to_json(),
    )

    confusion_key = HmacKey(issuer.public_key().raw, key_id=issuer.key_id)
    confused = refund.sign(confusion_key)
    _write_json(
        invalid / "alg-confusion.bundle.json",
        replace(bundles["committed-refund"], receipt=confused).to_json(),
    )

    checkpoint = json.loads(json.dumps(good))
    checkpoint["checkpoint"]["tree_size"] = 6
    checkpoint["inclusion"]["tree_size"] = 6
    _write_json(invalid / "checkpoint-forged.bundle.json", checkpoint)

    ordered = [receipts[name] for name, _, _ in scenarios]
    reordered = [ordered[1], ordered[0], *ordered[2:]]
    tree = MerkleTree(r.leaf_hash() for r in reordered)
    reordered_checkpoint = Checkpoint(
        log_id=LOG_ID,
        tree_size=len(reordered),
        root_hash=tree.root().hex(),
        issued_at=_BASE + timedelta(hours=2),
    ).sign(issuer)
    _write_json(
        invalid / "reordered-log.bundle.json",
        ReceiptBundle(
            receipt=refund,
            inclusion=InclusionProof(
                0, len(reordered), tuple(p.hex() for p in tree.inclusion_proof(0))
            ),
            checkpoint=reordered_checkpoint,
        ).to_json(),
    )
    _write_json(
        invalid / "leaf-moved.bundle.json",
        ReceiptBundle(
            receipt=refund,
            inclusion=InclusionProof(
                1, len(reordered), tuple(p.hex() for p in tree.inclusion_proof(1))
            ),
            checkpoint=reordered_checkpoint,
        ).to_json(),
    )

    _write_json(
        invalid / "unwitnessed.bundle.json",
        ReceiptBundle(
            receipt=refund,
            inclusion=InclusionProof(
                0,
                unwitnessed.tree_size,
                tuple(
                    p.hex()
                    for p in MerkleTree(
                        r.leaf_hash() for r in ordered[: unwitnessed.tree_size]
                    ).inclusion_proof(0)
                ),
            ),
            checkpoint=unwitnessed,
        ).to_json(),
    )

    fork_draft = replace(scenarios[6][1], outcome=Outcome(OutcomeStatus.COMMITTED, "stage:forged"))
    fork_receipt = fork_draft.with_log_anchor(LOG_ID, 6).sign(issuer)
    forked = [*ordered[:6], fork_receipt]
    fork_tree = MerkleTree(r.leaf_hash() for r in forked)
    fork_checkpoint = Checkpoint(
        log_id=LOG_ID,
        tree_size=7,
        root_hash=fork_tree.root().hex(),
        issued_at=_BASE + timedelta(hours=3),
    ).sign(issuer)
    _write_json(
        invalid / "split-view.bundle.json",
        ReceiptBundle(
            receipt=fork_receipt,
            inclusion=InclusionProof(6, 7, tuple(p.hex() for p in fork_tree.inclusion_proof(6))),
            checkpoint=fork_checkpoint,
        ).to_json(),
    )

    modified_rows = refund_rows.to_json()
    modified_rows["rows"][0]["row"]["after"]["status"] = "paid"
    _write_json(invalid / "row-modified.rows.json", modified_rows)
    moved_rows = refund_rows.to_json()
    moved_rows["rows"][1]["index"] = 1
    _write_json(invalid / "row-moved.rows.json", moved_rows)

    text = json.dumps(good, indent=2)
    (invalid / "duplicate-key.bundle.json").write_text(
        text.replace('"v": "ARC1-bundle",', '"v": "ARC1-bundle",\n  "v": "ARC1-bundle",', 1),
        encoding="utf-8",
    )
    (invalid / "float-amount.bundle.json").write_text(
        text.replace('"settled_usd": "0.00549500"', '"settled_usd": 0.005495', 1), encoding="utf-8"
    )
    unknown = json.loads(json.dumps(good))
    unknown["receipt"]["effect"]["confidence"] = "high"
    _write_json(invalid / "unknown-field.bundle.json", unknown)

    _write_json(out / "manifest.json", _manifest())


