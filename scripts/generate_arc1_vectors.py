"""Generate the ARC1 reference test vectors in ``vectors/arc1/``.

Everything here is deterministic: the keys come from fixed, published seeds
(test-only, never use them for anything real), every clock and identifier is
fixed, and Ed25519 signatures are deterministic. Running this twice writes
identical bytes, and ``tests/test_receipt_vectors.py`` regenerates the
vectors on every CI run and fails if a committed file differs from what the
code produces today.

Needs the ``cryptography`` package to sign (``uv sync`` installs it for
development). Verifying the vectors needs nothing but the standard library.

Usage::

    uv run python scripts/generate_arc1_vectors.py [--out vectors/arc1]
"""

