_README = """\
# ARC1 reference test vectors

Generated by [`scripts/generate_arc1_vectors.py`](../../scripts/generate_arc1_vectors.py).
Do not edit by hand. The test suite regenerates this directory on every run
and fails if a single byte differs
([`tests/test_receipt_vectors.py`](../../tests/test_receipt_vectors.py)). The
format is specified in [`docs/RECEIPTS.md`](../../docs/RECEIPTS.md).

> **The keys in `keys/` are test keys.** `issuer.seed` and `witness.seed`
> are Ed25519 private seeds, and `internal.hmac` is an HMAC secret. All three
> are published, and derived from public labels, so that anyone can reproduce
> these files. Never use them for anything else.

## Layout

- `canonical.json`: RFC 8785 cases. Inputs, their exact canonical UTF-8, and
  texts a strict decoder must refuse.
- `merkle.json`: the RFC 9162 eight-leaf reference tree. Every root, and
  every inclusion and consistency proof.
- `ed25519.json`: the RFC 8032 section 7.1 signatures, a wrong message, and
  an `S` at or above the group order.
- `keys/`: `issuer.pub` and `witness.pub`, the keys a verifier trusts;
  `internal.hmac`; and the test seeds.
- `log/receipts.jsonl`: a durable receipt log of seven receipts. Each line is
  one canonical receipt, and exactly one Merkle leaf.
- `log/receipts.jsonl.checkpoints`: the log's signed checkpoints at sizes 3,
  5 and 7.
- `log/consistency.json`: the consistency proof from size 3 to 7 that the
  witness checked before it cosigned size 7.
- `witness/cosignatures.jsonl`: the witness's cosignatures of sizes 3 and 7.
  Size 5 was never shown to it.
- `valid/`: bundles and row disclosures that verify.
- `invalid/`: each one broken in exactly one way.
- `manifest.json`: every command-line case, and the exit code it must produce.

## The receipts

A support agent works a tenant-partitioned orders database, under a
capability for one tenant:

0. `committed-refund`: refunds one order, 3 rows. Committed.
1. An address update. Committed.
2. A support note. Committed.
3. `refused-tenant-wipe`: a prompt-injected plan that zeroes every tenant's
   totals and deletes the audit trail, 229 rows. Refused, and rolled back.
4. `scoped-repair`: the one-row fix the refused plan should have been. Its
   `decision.repair_of` names receipt 3. Committed.
5. `recovered-commit`: resolved after a crash, from the escrow chain's commit
   marker. `recovered_committed`.
6. `halted-scope`: admitted by every check, and refused because the scope was
   halted.

## Running the cases

From this directory:

```console
$ agentgov verify-receipt valid/committed-refund.bundle.json --pubkey keys/issuer.pub \\
      --witness witness/cosignatures.jsonl --witness-pubkey keys/witness.pub \\
      --rows valid/committed-refund.rows.json
```

Each case in `manifest.json` gives the arguments, as paths relative to this
directory, and the exit code: 0 pass, 3 malformed, 4 receipt signature, 5 log
inclusion, 6 witness, 8 rows. A conforming verifier produces the same code
for every case.
"""


def seed(label: str) -> bytes:
    """A published test-only key seed. NEVER use these outside tests."""
    return hashlib.sha256(
        f"ARC1 test vector {label} key; never use outside tests".encode()
    ).digest()


def _uuid(label: str) -> str:
    return str(uuid.uuid5(_NAMESPACE, label))


def _digest(label: str) -> str:
    return hashlib.sha256(label.encode()).hexdigest()


class _Clock:
    """A clock that ticks a fixed step on every call, for deterministic output."""

    def __init__(self, start: datetime, step: timedelta) -> None:
        self._now, self._step = start, step

    def __call__(self) -> datetime:
        now, self._now = self._now, self._now + self._step
        return now


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


